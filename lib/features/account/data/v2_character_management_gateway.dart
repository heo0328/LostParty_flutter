import 'package:flutter/foundation.dart';
import '../domain/account_read_session.dart';
import '../domain/character_management_context.dart';
import '../domain/entities/local_game_account.dart';
import '../domain/repositories/character_management_gateway.dart';
import '../domain/scoped_cache_models.dart';
import 'local/scoped_command_key.dart';
import 'management_command_journal.dart';
import 'scoped_account_runtime.dart';

/// App-owned v2 write lane. Canonical order comes only from one v2 observation.
class V2CharacterManagementGateway extends ChangeNotifier
    implements ImmediateCharacterManagementGateway {
  V2CharacterManagementGateway(
    this.runtime,
    this.registrationId, {
    required this.otherWorkPending,
    this.metadata,
    this.journal = const SecureManagementJournalStorage(),
  }) {
    runtime.session.addListener(_sessionChanged);
  }
  final ScopedAccountRuntime runtime;
  final String registrationId;
  final bool Function() otherWorkPending;
  final Iterable<CacheCharacterObservation> Function()? metadata;
  final ManagementJournalStorage journal;
  AccountReadScope? _session;
  StorageScope? _scope;
  CharacterManagementContext? _context;
  Map<String, dynamic>? _pendingCommand;
  Map<String, dynamic>? get _command => _pendingCommand;
  set _command(Map<String, dynamic>? value) {
    _pendingCommand = value;
    runtime.releaseManagementCommand(this);
    if (value != null && _scope != null) {
      runtime.holdManagementCommand(this, _scope!, registrationId);
    }
  }

  DateTime? _retryAt;
  final Map<String, int> _ids = {};
  bool _busy = false, _disposed = false;
  Set<String> _allowedResidueRemoval = {};
  @override
  void allowMissingSelectionRemoval() =>
      _allowedResidueRemoval = _context?.residueIds.toSet() ?? {};
  int _epoch = 0;
  bool _isMainRegistration = false;

  String get _path => '/v2/me/game-accounts/$registrationId/character-settings';
  @override
  bool get current =>
      !_disposed &&
      runtime.canRead &&
      _context != null &&
      _session == accountReadScope(runtime.session) &&
      _scope == runtime.scope;
  @override
  bool get busy => _busy;
  @override
  bool get pending => _command != null;
  void _sessionChanged() {
    if (_session != null &&
        (!runtime.canRead || _session != accountReadScope(runtime.session))) {
      _epoch++;
      _context = null;
      _command = null;
      _allowedResidueRemoval = {};
      _ids.clear();
      notifyListeners();
    }
  }

  void _guard(int epoch, AccountReadScope member, StorageScope scope) {
    if (_disposed || epoch != _epoch) {
      throw const AccountReadException('STALE_READ');
    }
    runtime.requireCurrent(member, scope);
  }

  Future<CharacterManagementContext> _get(void Function() guard) async {
    final json = await runtime.api.request(_path);
    guard();
    try {
      final value = CharacterManagementContext.fromJson(json!);
      if (value.registrationId != registrationId ||
          _context != null && value.accountId != _context!.accountId) {
        throw const FormatException('Management scope mismatch');
      }
      return value;
    } on FormatException {
      throw const AccountReadException('INVALID_RESPONSE');
    } on TypeError {
      throw const AccountReadException('INVALID_RESPONSE');
    }
  }

  Map<String, dynamic>? _decodeJournal(String? raw) {
    if (raw == null) return null;
    try {
      final value = jsonDecode(raw) as Map<String, dynamic>;
      if (value.length != 5 ||
          value['schema'] != 1 ||
          value['registration_id'] != registrationId ||
          value['key'] is! String ||
          !RegExp(
            r'^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$',
          ).hasMatch(value['key'] as String) ||
          value['body'] is! Map<String, dynamic> ||
          value['acknowledged'] is! bool) {
        throw const FormatException('Invalid journal');
      }
      // CAS/body was generated by this client; malformed saved commands fail closed.
      final body = value['body'] as Map<String, dynamic>;
      final expected = [
        'activity_character_ids',
        'representative_character_id',
        'expected_registration_version',
        'expected_settings_version',
        'expected_ownership_revision',
        'expected_roster_revision',
        'expected_order_digest',
      ];
      if (!expected.every(body.containsKey) ||
          body.keys.any(
            (k) =>
                !expected.contains(k) &&
                k != 'ordered_character_ids' &&
                k != 'policy_version',
          )) {
        throw const FormatException('Invalid journal body');
      }
      CharacterManagementContext.validateCommandBody(body);
      return value;
    } catch (_) {
      throw const AccountReadException('LOCAL_COMMAND_INVALID');
    }
  }

  @override
  Future<CharacterManagementSnapshot> load() async {
    if (_busy) throw const AccountReadException('REQUEST_IN_PROGRESS');
    _busy = true;
    final epoch = _epoch,
        member = accountReadScope(runtime.session),
        scope = runtime.scope;
    void guard() => _guard(epoch, member, scope);
    try {
      final saved = _decodeJournal(await journal.read(scope, registrationId));
      guard();
      final context = await _get(guard);
      final isMain = context.isMain;
      guard();
      _session = member;
      _scope = scope;
      _command = saved;
      _context = context;
      _isMainRegistration = isMain;
      return _snapshot();
    } finally {
      _busy = false;
      if (!_disposed) notifyListeners();
    }
  }

  CharacterManagementSnapshot _snapshot() {
    final context = _context!;
    for (final row in context.characters) {
      _ids.putIfAbsent(row.id, () => _ids.length + 1);
    }
    final info = {
      for (final row in metadata?.call() ?? <CacheCharacterObservation>[])
        row.characterId: row,
    };
    final chars = <LocalAccountCharacter>[];
    for (final row in context.characters) {
      final observed = info[row.id];
      final profile = observed == null
          ? null
          : jsonDecode(observed.profileJson) as Map;
      chars.add(
        LocalAccountCharacter(
          id: _ids[row.id]!,
          serverCharacterId: row.id,
          serverName: observed?.serverName ?? '',
          characterName: row.name,
          characterLevel: profile?['character_level'] as int? ?? 0,
          characterClassName: profile?['class_name'] as String? ?? '직업 정보 미확인',
          itemLevel: double.tryParse(row.level ?? ''),
          combatPower: null,
          isVisible: true,
          displayOrder: row.rank,
          isRosterMissing: !row.usable,
        ),
      );
    }
    final selected = {
      for (final id in context.activityIds)
        if (context.orderedIds.contains(id)) _ids[id]!,
    };
    final invalid =
        context.residueIds.length +
        context.characters
            .where((c) => context.activityIds.contains(c.id) && !c.usable)
            .length;
    final rep = context.characters
        .where(
          (c) =>
              c.id == context.representativeId &&
              c.usable &&
              context.activityIds.contains(c.id),
        )
        .firstOrNull;
    return CharacterManagementSnapshot(
      account: LocalGameAccount(
        id: 1,
        label: '내 원정대',
        isMain: _isMainRegistration,
        lookupCharacterName: '',
        representativeCharacterId: rep == null ? null : _ids[rep.id],
        displayLimit: 200,
        characters: chars,
      ),
      selectedIds: selected,
      usableIds: {
        for (final c in context.characters)
          if (c.usable) _ids[c.id]!,
      },
      hasNiceGroup: false,
      initialSelectionRequired:
          context.state == 'unconfigured' && context.activityIds.isEmpty,
      canonicalOrder: true,
      warning:
          invalid > 0 ||
              (_isMainRegistration &&
                  context.representativeId != null &&
                  rep == null)
          ? _isMainRegistration
                ? '사용할 수 없거나 목록에서 사라진 선택이 있습니다. 사용 캐릭터와 대표를 확인해 주세요.'
                : '사용할 수 없거나 목록에서 사라진 선택이 있습니다. 사용 캐릭터를 확인해 주세요.'
          : null,
      residueCount: context.residueIds.length,
    );
  }

  @override
  Future<CharacterManagementSnapshot> save({
    required List<int> selectedIds,
    required int? representativeId,
    required int displayLimit,
    bool saveDisplayOrder = true,
  }) async {
    if (!current) throw const AccountReadException('STALE_READ');
    if (_busy || otherWorkPending()) {
      throw const AccountReadException('REQUEST_IN_PROGRESS');
    }
    if (_retryAt != null && DateTime.now().isBefore(_retryAt!)) {
      throw AccountReadException('REQUEST_IN_PROGRESS', retryAt: _retryAt);
    }
    final epoch = _epoch, member = _session!, scope = _scope!;
    void guard() => _guard(epoch, member, scope);
    final lock = Object();
    runtime.lockCharacterSettings(lock);
    _busy = true;
    notifyListeners();
    try {
      if (_command == null) {
        if (!_allowedResidueRemoval.containsAll(_context!.residueIds)) {
          throw const AccountReadException(
            'CHARACTER_SELECTION_REPAIR_REQUIRED',
          );
        }
        String uuid(int id) =>
            _ids.entries.firstWhere((e) => e.value == id).key;
        final selected = selectedIds.map(uuid).toList(),
            rep = representativeId == null ? null : uuid(representativeId);
        if (!_isMainRegistration && rep != null) {
          throw const AccountReadException('MAIN_REGISTRATION_REQUIRED');
        }
        final body = _context!.command(
          selected,
          rep,
          ordered: saveDisplayOrder
              ? selected
                    .where(
                      (id) =>
                          id !=
                          (_isMainRegistration
                              ? rep ??
                                    _context!.automaticRepresentative(selected)
                              : null),
                    )
                    .toList()
              : null,
        );
        final command = {
          'schema': 1,
          'registration_id': registrationId,
          'key': newScopedCommandKey(),
          'body': body,
          'acknowledged': false,
        };
        await journal.write(scope, registrationId, jsonEncode(command));
        guard();
        _command = command;
      }
      if (_command!['acknowledged'] != true) {
        try {
          final response = await runtime.api.request(
            _path,
            method: 'PUT',
            body: Map<String, dynamic>.from(_command!['body'] as Map),
            idempotencyKey: _command!['key'] as String,
          );
          guard();
          final ack = CharacterManagementContext.fromJson(
            response!,
            historical: (_command!['body'] as Map)['policy_version'] == null,
          );
          if (ack.registrationId != registrationId ||
              ack.accountId != _context!.accountId) {
            throw const FormatException('ACK scope mismatch');
          }
          final acknowledged = {..._command!, 'acknowledged': true};
          await journal.write(scope, registrationId, jsonEncode(acknowledged));
          guard();
          _command = acknowledged;
        } on AccountReadException catch (e) {
          if (e.retryAt != null || e.retryAfter != null) {
            _retryAt = e.retryAt ?? DateTime.now().add(e.retryAfter!);
          }
          if ([
            'CONTRACT_POLICY_CHANGED',
            'MAIN_REGISTRATION_CHANGED',
            'REVISION_CONFLICT',
            'IDEMPOTENCY_EXPIRED',
            'IDEMPOTENCY_CONFLICT',
            'OWNERSHIP_REQUIRED',
            'CHARACTER_UNUSABLE',
            'CHARACTER_NOT_FOUND',
            'IDENTITY_CONFLICT',
            'EMPTY_ACTIVITY_SELECTION',
            'REPRESENTATIVE_REQUIRED',
            'INVALID_REQUEST',
          ].contains(e.code)) {
            // Definite rejection: GET before a new explicit user attempt.
            final context = await _get(guard);
            final isMain = context.isMain;
            await journal.write(scope, registrationId, null);
            guard();
            _context = context;
            _isMainRegistration = isMain;
            _command = null;
          }
          rethrow;
        }
      }
      final context = await _get(guard); // ACK may be a historical replay.
      final isMain = context.isMain;
      await journal.write(scope, registrationId, null);
      guard();
      _context = context;
      _isMainRegistration = isMain;
      _command = null;
      runtime.invalidateReads();
      return _snapshot();
    } finally {
      runtime.unlockCharacterSettings(lock);
      _busy = false;
      if (!_disposed) notifyListeners();
    }
  }

  @override
  void dispose() {
    runtime.releaseManagementCommand(this);
    _disposed = true;
    _epoch++;
    runtime.session.removeListener(_sessionChanged);
    super.dispose();
  }
}
