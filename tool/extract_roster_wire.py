"""Generate the recruitment validation projection from the deployed Issue17 contract.

Original journal validation remains pinned separately; no stored request is rewritten.
Usage: python3 tool/extract_roster_wire.py path/to/two-cycle.openapi.yaml
"""
import hashlib
import json
import sys
from pathlib import Path
import extract_cycle_group_wire as base

PIN = '864de38b53ec23a305074bb3844a7a603ba1f992815427fdba3e6931793119b6'


def main():
    raw = Path(sys.argv[1]).read_bytes()
    assert hashlib.sha256(raw).hexdigest() == PIN
    base.BLOB = hashlib.sha1(b'blob ' + str(len(raw)).encode() + b'\0' + raw).hexdigest()
    base.SOURCE = 'Issue17 source 16c9cd4b9016a881bbb26c8438f3347049603902 / SHA256 ' + PIN
    base.main()
    dest = base.DEST / 'beta_wire_schema.g.dart'
    generated = dest.read_text(encoding='utf-8')
    wire = json.loads(generated.split("r'''", 1)[1].rsplit("'''", 1)[0])
    api = json.loads(raw)
    path = '/v2/me/raid-room-character-issues'
    op = api['paths'][path]['get']
    wire['operations'].append(base.rewrite({
        'id': 'rosterIssueSummary', 'method': 'GET', 'path': path,
        'query': [{k: p[k] for k in ('name', 'required', 'schema')}
                  for p in op['parameters'] if p['in'] == 'query'],
        'request': None,
        'responses': {'200': op['responses']['200']['content']['application/json']['schema']},
    }))
    # Include the summary and standalone metadata validation roots as well.
    needed = {n for n in api['components']['schemas']
              if n.startswith('Roster') and not n.startswith(('RosterIssues_', 'RosterPresence_'))}
    while needed:
        name = needed.pop()
        definition = api['components']['schemas'][name]
        wire['definitions'][name] = base.rewrite(definition)
        needed.update(n for n in base.refs(definition) if n not in wire['definitions'])
    dest.write_text('// Generated by tool/extract_roster_wire.py; source SHA256 ' + PIN + '.\n'
                    "const betaWireSchemaJson = r'''\n" +
                    json.dumps(wire, ensure_ascii=False, indent=2) + "\n''';\n", encoding='utf-8')
    print('Issue17 projection:', len(wire['operations']), 'operations')


if __name__ == '__main__':
    main()
