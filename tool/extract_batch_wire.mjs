// Extend the existing roster projection without rewriting saved-request schemas.
// node tool/extract_batch_wire.mjs path/to/pinned/two-cycle.openapi.yaml
import fs from 'node:fs';
import crypto from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const pin = '2c51d2f206100e9a305bafa6dd537a1b1b40cc23f9cf1ac6f65d254a4ff5faf7';
const source = '44eb4ba34844eb81801608ed5953cf3bb1ba0852';
const raw = fs.readFileSync(process.argv[2]);
if (crypto.createHash('sha256').update(raw).digest('hex') !== pin) throw Error('Wrong pinned batch contract');
const api = JSON.parse(raw);
const dest = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../lib/features/recruitment_list/data/beta/beta_wire_schema.g.dart');
const previous = fs.readFileSync(dest, 'utf8');
const wire = JSON.parse(previous.split("r'''\n")[1].split("''';")[0]);
const sorted = v => Array.isArray(v) ? v.map(sorted) : v && typeof v === 'object' ? Object.fromEntries(Object.keys(v).sort().map(k => [k, sorted(v[k])])) : v;
const stable = v => JSON.stringify(sorted(v));
function rewrite(v) {
  if (Array.isArray(v)) return v.map(rewrite);
  if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, k === '$ref' ? '#/$defs/' + x.split('/').at(-1) : rewrite(x)]));
  return v;
}
function refs(v) {
  if (!v || typeof v !== 'object') return [];
  return [...(v.$ref ? [v.$ref.split('/').at(-1)] : []), ...Object.values(v).flatMap(refs)];
}
const needed = new Set();
for (const [suffix, method] of [['batch-completion-context', 'get'], ['batch-completions', 'post'], ['batch-personal-completion-departure-context', 'get'], ['batch-personal-completion-departures', 'post']]) {
  const template = '/v2/raid-rooms/{room_id}/' + suffix;
  const op = api.paths[template][method];
  const projected = rewrite({id: op.operationId, method: method.toUpperCase(), path: template,
    query: (op.parameters ?? []).filter(p => p.in === 'query').map(p => ({name: p.name, required: p.name === 'contract_profile' || p.required, schema: p.name === 'contract_profile' ? {type: 'string', const: 'beta-recruitment-1'} : p.schema})),
    request: op.requestBody?.content?.['application/json']?.schema ?? null,
    responses: Object.fromEntries(Object.entries(op.responses).filter(([s, r]) => s.startsWith('2') && r.content).map(([s, r]) => [s, r.content['application/json'].schema]))});
  const old = wire.operations.find(o => o.method === projected.method && o.path === template);
  if (old && JSON.stringify(old) !== JSON.stringify(projected)) throw Error('Changed batch operation');
  if (!old) wire.operations.push(projected);
  refs(projected).forEach(n => needed.add(n));
}
const seen = new Set();
while (needed.size) {
  const name = [...needed].sort()[0]; needed.delete(name);
  if (seen.has(name)) continue;
  seen.add(name);
  const definition = rewrite(api.components.schemas[name]);
  if (!definition) throw Error('Missing definition ' + name);
  // Existing shared DTOs remain byte-equivalent as JSON; never replace them.
  if (name in wire.definitions) {
    if (stable(wire.definitions[name]) !== stable(definition)) throw Error('Changed shared definition ' + name);
  } else wire.definitions[name] = definition;
  refs(definition).forEach(n => { if (!seen.has(n)) needed.add(n); });
}
fs.writeFileSync(dest, `// Generated by tool/extract_batch_wire.mjs; source ${source}; SHA256 ${pin}.\nconst betaWireSchemaJson = r'''\n${JSON.stringify(wire, null, 2)}\n''';\n`);
console.log(`Pinned batch projection: ${wire.operations.length} operations, ${seen.size} reachable definitions`);
